(async () => {
  const lines = [];
  const assert = (condition, name) => { if (!condition) throw new Error(name); lines.push('PASS ' + name); };
  const settle = () => new Promise(resolve => setTimeout(resolve, 1200));
  const root = () => document.querySelector('[data-mgq-preview]')?.shadowRoot;
  try {
    await new Promise(resolve => window.addEventListener('load', resolve, { once: true }));
    await settle();
    const body = document.querySelector('.quest-cnt');
    const formula = body.querySelector('img');
    const width = formula.getBoundingClientRect().width;
    assert(document.querySelectorAll('.mgq-launch').length === 2, '单题和列表入口各一个');
    assert(getComputedStyle(body).fontSize === '22px', '默认22px');
    assert(getComputedStyle(document.querySelector('.outside')).fontSize === '14px', '不影响操作栏');
    assert(getComputedStyle(body.querySelector('sup')).fontSize === '15.84px', '保留上下标比例');
    await MathGaoSettings.update({background:'grass',font:'serif',ink:'navy'}); await settle();
    assert(getComputedStyle(body).backgroundColor === 'rgb(232, 240, 224)', '原题面草绿色');
    assert(getComputedStyle(document.body).backgroundColor === 'rgb(223, 232, 215)', '页面背景同步变色');
    assert(getComputedStyle(body).fontFamily.includes('Noto Serif SC'), '原页切换宋体');
    assert(getComputedStyle(body).color === 'rgb(32, 60, 84)', '文字颜色切换');
    document.querySelector('.mgq-launch').click(); await settle();
    assert(getComputedStyle(root().querySelector('.paper')).backgroundColor === 'rgb(232, 240, 224)', '展示题面同步背景');
    const backgroundControl=root().querySelector('[data-preset="background"]');
    backgroundControl.value='cream'; backgroundControl.dispatchEvent(new Event('change',{bubbles:true})); await settle();
    assert(getComputedStyle(body).backgroundColor === 'rgb(255, 248, 232)', '展示窗口切换实时同步原页');
    assert((await MathGaoSettings.read()).background === 'cream', '背景设置保存');
    root().querySelector('[data-action="close"]').click();
    await MathGaoSettings.update({enabled:false}); await settle();
    assert(getComputedStyle(document.body).backgroundColor === 'rgb(238, 238, 238)', '关闭美化还原页面背景');
    await MathGaoSettings.reset(); await settle();
    await MathGaoSettings.update({ fontSize: 32 }); await settle();
    assert(Math.abs(formula.getBoundingClientRect().width / width - 32 / 22) < .02, '公式跟随字号等比缩放');
    await MathGaoSettings.update({ enabled: false }); await settle();
    assert(getComputedStyle(body).fontSize === '14px', '关闭恢复原字号');
    assert(Math.abs(formula.getBoundingClientRect().width - 40) < .1, '关闭恢复原公式尺寸');
    await MathGaoSettings.reset(); await settle();
    assert(Math.abs(formula.getBoundingClientRect().width - width) < .1, '多次切换无累计放大');
    document.querySelector('.mgq-launch').click(); await settle();
    let shadow = root();
    assert(shadow.querySelectorAll('.question img').length === 2, '题面保留公式及题图');
    assert(!shadow.querySelector('.question').textContent.includes('禁止出现'), '不带隐藏答案');
    assert(shadow.querySelectorAll('td').length === 4, '保留表格结构');
    assert(shadow.querySelector('i').textContent === 'x', '保留数学斜体');
    assert(shadow.querySelector('.paper').getBoundingClientRect().width <= window.innerWidth, '宽度不超窗口');
    const control = shadow.querySelector('[data-key="width"]'); control.value = 800; control.dispatchEvent(new Event('input', { bubbles: true })); await settle();
    assert((await MathGaoSettings.read()).width === 800, '展示设置写入存储');
    shadow.querySelector('[data-action="hide"]').click();
    assert(shadow.querySelector('.toolbar').hidden, '隐藏工具栏');
    shadow.querySelector('.restore').click(); assert(!shadow.querySelector('.toolbar').hidden, '恢复工具栏');
    document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
    assert(!root(), 'Esc关闭且移除展示容器');
    document.querySelectorAll('.mgq-launch')[1].click(); await settle(); shadow = root();
    assert(!/^\s*1\s*\./.test(shadow.querySelector('.question').textContent), '移除列表序号');
    assert(shadow.querySelector('.question').textContent.includes('D．4'), '保留全部选项');
    shadow.querySelector('[data-action="close"]').click();
    const item = document.createElement('div'); item.className = 'quesdiv'; item.innerHTML = '<div class="exam-item__cnt">2 . 新增题目</div>'; document.body.append(item); await settle();
    assert(document.querySelectorAll('.mgq-launch').length === 3, '动态新增题目自动适配');
    item.querySelector('.exam-item__cnt').append(document.createElement('span')); await settle();
    assert(document.querySelectorAll('.mgq-launch').length === 3, '重复扫描不重复插按钮');
    item.remove(); await settle(); assert(document.querySelectorAll('.mgq-launch').length === 2, '换页移除旧入口');
    await MathGaoSettings.update({ enabled: false }); document.querySelector('.mgq-launch').click(); await settle();
    assert(getComputedStyle(root().querySelector('.question')).fontSize === '22px', '原页关闭时仍可独立展示');
    root().querySelector('[data-action="close"]').click();
    await MathGaoSettings.reset();
    const popupHtml = await (await fetch('/extension/popup.html')).text();
    const frame = document.createElement('iframe');
    const loaded = new Promise(resolve => frame.addEventListener('load', resolve, {once:true}));
    frame.srcdoc = popupHtml.replace('<head>', '<head><base href="/extension/">').replace('<script src="settings.js">', '<script src="/tests/storage-mock.js"></script><script src="settings.js">');
    document.body.append(frame); await loaded; await settle();
    const popup = frame.contentDocument;
    assert(popup.getElementById('enabled').checked && popup.getElementById('fontSize').value === '22', '设置弹窗读取默认设置');
    assert(popup.getElementById('background').options.length===6 && popup.getElementById('font').options.length===5 && popup.getElementById('ink').options.length===4, '提供六套背景五种字体四种文字颜色');
    const presetControl=popup.getElementById('background');presetControl.value='grass';presetControl.dispatchEvent(new frame.contentWindow.Event('change',{bubbles:true}));await settle();
    assert((await frame.contentWindow.MathGaoSettings.read()).background==='grass', '弹窗背景选择保存');
    popup.getElementById('enabled').click();
    const fontControl = popup.getElementById('fontSize'); fontControl.value = '28'; fontControl.dispatchEvent(new frame.contentWindow.Event('input',{bubbles:true})); await settle();
    const saved = await frame.contentWindow.MathGaoSettings.read();
    assert(saved.enabled === false && saved.fontSize === 28, '设置弹窗开关和滑块保存');
    popup.getElementById('reset').click(); await settle();
    assert(popup.getElementById('enabled').checked && popup.getElementById('fontSize').value === '22' && popup.getElementById('background').value==='white', '弹窗恢复默认值');
    frame.remove();
    document.getElementById('result').textContent = lines.join('\n') + '\n全部通过：' + lines.length;
    document.documentElement.dataset.testStatus = 'passed';
  } catch (error) { document.getElementById('result').textContent = lines.join('\n') + '\nFAIL ' + error.message; document.documentElement.dataset.testStatus = 'failed'; }
})();
